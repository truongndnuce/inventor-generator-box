using System.Globalization;
using System.Text;

namespace Cadflow.Api;

/// <summary>The lines <c>FirstLine..LastLine</c> (1-based, inclusive) of the generated text that were produced by the model element <see cref="Path"/>.</summary>
public sealed record LineEntry(int FirstLine, int LastLine, string Path);

/// <summary>A generated script and the table that maps its lines back to model elements.</summary>
public sealed record DesignOutput(string Text, IReadOnlyList<LineEntry> LineMap)
{
    /// <summary>The model path of the most specific element that produced <paramref name="line"/> (1-based), or null for lines that belong to no element (BEGIN_FORM, blank lines, comments).</summary>
    public string? Find(int line)
    {
        LineEntry? best = null;
        foreach (var e in LineMap)
        {
            if (line < e.FirstLine || line > e.LastLine) continue;
            if (best == null || e.LastLine - e.FirstLine <= best.LastLine - best.FirstLine) best = e;   // a narrower entry (or a later one of equal size) is more specific
        }
        return best?.Path;
    }

    public LineEntry? Entry(string path) => LineMap.FirstOrDefault(e => e.Path == path);
}

/// <summary>Thrown when a model with errors is given to the generator; <see cref="Issues"/> lists the errors and the warnings.</summary>
public sealed class InvalidDesignException(IReadOnlyList<DesignIssue> issues)
    : Exception("The design has errors: " + string.Join("; ", issues.Where(i => !i.IsWarning).Select(i => $"{i.Path}: {i.Message}")))
{
    public IReadOnlyList<DesignIssue> Issues { get; } = issues;
}

/// <summary>
/// Turns a <see cref="DesignModel"/> into a .gea script (docs/superpowers/specs/2026-11-11-gea-designer-design.md, section 3).
/// The output is deterministic (fixed section order, LF line endings, two-space indent, one blank line between sections) so it can be compared with a golden file.
/// Text typed by the author goes only into quoted strings (escaped), expressions (checked by <see cref="DesignValidator"/>) and the build text, never into a comment.
/// The !@DESIGNER block (the model itself) is added by a separate step (DesignBlock), not here.
/// </summary>
public static class DesignGenerator
{
    public static DesignOutput Generate(DesignModel model)
    {
        var issues = DesignValidator.Validate(model);
        if (issues.Any(i => !i.IsWarning)) throw new InvalidDesignException(issues);

        var w = new Writer();
        var product = model.Product;

        // ---- header
        w.L("! ============================================================================");
        w.L("! Generated by the Product Designer of CAD Automation.");
        w.L("! Open this file in the Designer to change it. Text edited by hand is detected, and the Designer");
        w.L("! asks before it drops those edits.");
        w.L("! ============================================================================");
        int h0 = w.Next;
        w.L("GEA_VERSION 1");
        w.L($"PRODUCT_NAME {Q(product.Name)}");
        w.L($"PARAM_PREFIX {product.Prefix}");
        w.L($"TARGET {product.Target}");
        w.Entry("product", h0, w.Next - 1);
        w.L();

        // ---- FORM
        w.L("BEGIN_FORM");
        w.L();

        if (model.Groups.Count > 0)
        {
            w.L("  ! Parameters: the input fields of the order form, in groups. A field inside IF ... END_IF is shown only while the condition is true.");
            for (int g = 0; g < model.Groups.Count; g++)
            {
                var group = model.Groups[g];
                int g0 = w.Next;
                w.L($"  BEGIN_GROUP {Q(group.Title)}");
                for (int p = 0; p < group.Params.Count; p++)
                {
                    var param = group.Params[p];
                    var path = $"groups[{g}].params[{p}]";
                    int p0 = w.Next;
                    if (!string.IsNullOrWhiteSpace(param.VisibleWhen))
                    {
                        w.L($"    IF {param.VisibleWhen!.Trim()}");
                        w.Entry(path + ".visibleWhen", p0, p0);
                        w.L("      " + ParamStatement(param));
                        w.L("    END_IF");
                    }
                    else
                        w.L("    " + ParamStatement(param));
                    w.Entry(path, p0, w.Next - 1);
                }
                w.L("  END_GROUP");
                w.Entry($"groups[{g}]", g0, w.Next - 1);
                w.L();
            }
        }

        if (model.Vars.Count > 0)
        {
            w.L("  ! Variables: values computed from the parameters, for use in the rules below (a variable is valid only in this block).");
            var firstOfVar = new int[model.Vars.Count];
            for (int v = 0; v < model.Vars.Count; v++)
            {
                firstOfVar[v] = w.Next;
                w.L($"  DECLARE_VARIABLE {model.Vars[v].Type} {model.Vars[v].Name}");
            }
            for (int v = 0; v < model.Vars.Count; v++)
            {
                int a = w.Next;
                w.L($"  {model.Vars[v].Name} = {model.Vars[v].Expr.Trim()}");
                w.Entry($"vars[{v}].expr", a, a);
            }
            // each variable is two separate lines (its declaration and its assignment): map the declaration to vars[v], the assignment keeps its more specific entry
            for (int v = 0; v < model.Vars.Count; v++) w.Entry($"vars[{v}]", firstOfVar[v], firstOfVar[v]);
            w.L();
        }

        if (model.Rules.Count > 0)
        {
            w.L("  ! Rules: each ASSERT must hold, otherwise the order form shows its message (a rule marked WARN only warns).");
            for (int r = 0; r < model.Rules.Count; r++)
            {
                var rule = model.Rules[r];
                int a = w.Next;
                w.L($"  ASSERT {rule.Expr.Trim()} {Q(rule.Message)}{(rule.Warn ? " WARN" : "")}");
                w.Entry($"rules[{r}]", a, a);
            }
            w.L();
        }

        w.L("END_FORM");
        w.L();

        // ---- BUILD
        w.L("BEGIN_BUILD");
        w.L();
        var raws = model.Steps.Select((s, i) => (Step: s, Index: i))
            .Select(x => (x.Index, Lines: RawLines(x.Step.Text)))
            .Where(x => x.Lines.Count > 0)
            .ToList();
        if (raws.Count == 0)
            w.L("  ! (no build steps yet)");
        else
        {
            w.L("  ! Build steps (text).");
            for (int i = 0; i < raws.Count; i++)
            {
                if (i > 0) w.L();
                int a = w.Next;
                foreach (var line in raws[i].Lines) w.L(line);
                w.Entry($"steps[{raws[i].Index}]", a, w.Next - 1);
            }
        }
        w.L();
        w.L("END_BUILD");

        return new DesignOutput(w.Text(), w.Map);
    }

    // ------------------------------------------------------------------ one parameter statement

    private static string ParamStatement(DesignParam p)
    {
        var sb = new StringBuilder();
        switch (p.Type)
        {
            case "CHECKBOX":
                sb.Append("CHECKBOX_PARAM ").Append(p.Name).Append(' ').Append(p.Default);
                break;
            case "RADIO":
                sb.Append("RADIOBUTTON_PARAM ").Append(p.Name);
                foreach (var o in p.Options!) sb.Append(' ').Append(Q(o));
                break;
            case "STRING":
                sb.Append("USER_INPUT_PARAM ").Append(p.Name).Append(" STRING ").Append(Q(p.Default ?? ""));
                break;
            default:
            {
                sb.Append("USER_INPUT_PARAM ").Append(p.Name).Append(' ').Append(p.Type).Append(' ')
                  .Append(Num(double.Parse(p.Default!, NumberStyles.Float, CultureInfo.InvariantCulture)));
                if (p.Type == "LENGTH") sb.Append(' ').Append(string.IsNullOrEmpty(p.Unit) ? "mm" : p.Unit);
                else if (p.Type == "ANGLE") sb.Append(' ').Append(string.IsNullOrEmpty(p.Unit) ? "deg" : p.Unit);
                // MIN / MAX / STEP are written without a unit: the language reads them in the unit of the parameter
                if (p.Min is { } min) sb.Append(" MIN ").Append(Num(min));
                if (p.Max is { } max) sb.Append(" MAX ").Append(Num(max));
                if (p.Step is { } step) sb.Append(" STEP ").Append(Num(step));
                if (p.Required) sb.Append(" REQUIRED");
                break;
            }
        }

        if (p.Type == "STRING" && p.Required) sb.Append(" REQUIRED");
        if (!string.IsNullOrEmpty(p.Label)) sb.Append(" LABEL ").Append(Q(p.Label));
        if (!string.IsNullOrEmpty(p.Tooltip)) sb.Append(" TOOLTIP ").Append(Q(p.Tooltip));
        if (p.Type == "RADIO" && !string.IsNullOrEmpty(p.Default) && p.Default != p.Options![0])
            sb.Append(" DEFAULT ").Append(Q(p.Default));
        return sb.ToString();
    }

    // ------------------------------------------------------------------ helpers

    /// <summary>A quoted string of the language: backslash and quote are escaped (the lexer reads \\ and \"). Control characters never get here (the validator refuses them).</summary>
    private static string Q(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    /// <summary>Shortest text that reads back as the same number, with a decimal point whatever the culture.</summary>
    private static string Num(double v) => v.ToString("R", CultureInfo.InvariantCulture);

    /// <summary>The lines of a raw build text: LF endings, blank lines at both ends removed, trailing spaces removed, every non-empty line indented two spaces.</summary>
    private static List<string> RawLines(string? text)
    {
        var lines = (text ?? "").Replace("\r\n", "\n").Replace('\r', '\n').Split('\n').Select(l => l.TrimEnd()).ToList();
        while (lines.Count > 0 && lines[0].Length == 0) lines.RemoveAt(0);
        while (lines.Count > 0 && lines[^1].Length == 0) lines.RemoveAt(lines.Count - 1);
        return lines.Select(l => l.Length == 0 ? l : "  " + l).ToList();
    }

    /// <summary>Collects the lines and the line map while the file is written.</summary>
    private sealed class Writer
    {
        private readonly StringBuilder _sb = new();
        private int _lines;

        public List<LineEntry> Map { get; } = new();

        /// <summary>Number of the line the next <see cref="L"/> call writes (1-based).</summary>
        public int Next => _lines + 1;

        public void L(string text = "")
        {
            _sb.Append(text).Append('\n');
            _lines++;
        }

        public void Entry(string path, int first, int last) => Map.Add(new LineEntry(first, last, path));

        public string Text() => _sb.ToString();
    }
}
